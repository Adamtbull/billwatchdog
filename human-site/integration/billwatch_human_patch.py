#!/usr/bin/env python3
"""Add the BillWatch human pages to an assembled Pages _worker.js. Safe to run on every build.

The live _worker.js is generated by build/make_worker.py, so a hand edit to it is lost on the
next rebuild. Run this script after make_worker.py, every time (best: as make_worker.py's last
step). It pastes billwatch-human.mjs into the worker inline, so the zip upload needs no module
imports, and adds the dispatch lines at the top of the fetch handler. It first removes its own
earlier output, so running it any number of times gives the same file.

    python3 billwatch_human_patch.py PATH/TO/_worker.js [PATH/TO/billwatch-human.mjs]
    python3 billwatch_human_patch.py --check PATH/TO/_worker.js     exit 1 unless already patched
    python3 billwatch_human_patch.py --remove PATH/TO/_worker.js    take the human pages back out
    python3 billwatch_human_patch.py --homepage on PATH/TO/_worker.js   one-off override (previews)

The bundle defaults to billwatch-human.mjs next to this script. Nothing here touches the
network, Cloudflare or any secret; it only rewrites the file it is given.
"""
import argparse
import re
import sys
from pathlib import Path

# The homepage switch. False: "/" keeps the current agent homepage. True: "/" serves the human
# homepage. Change it here, not in _worker.js: the next rebuild would undo an edit there.
HUMAN_HOMEPAGE = False

BEGIN_TOP = "// >>> BillWatch human pages: added by billwatch_human_patch.py. Edit the script, not this block."
END_TOP = "// <<< BillWatch human pages"
BEGIN_DISPATCH = "// >>> BillWatch human pages dispatch"
END_DISPATCH = "// <<< BillWatch human pages dispatch"
EXPORT_LINE = "export { BillWatchHuman };"
# Names the patch defines. None may already exist in the worker.
OWN_NAMES = ("BillWatchHuman", "HUMAN_HOMEPAGE", "humanResponse")
IDENTIFIER = re.compile(r"[A-Za-z_$][\w$]*")
FETCH = re.compile(r"^(?P<indent>[ \t]*)async\s+fetch\s*\((?P<params>[^)]*)\)\s*\{[ \t]*$", re.M)
EXPORT_DEFAULT = re.compile(r"^export\s+default\b", re.M)


class PatchError(Exception):
    """The worker or bundle is not in the shape this script expects. Nothing was written."""


def _block(begin, end):
    return re.compile(r"^[ \t]*" + re.escape(begin) + r"\n.*?^[ \t]*" + re.escape(end) + r"\n", re.M | re.S)


def remove_patch(worker):
    """Return the worker with this script's blocks removed (exactly the pre-patch text)."""
    for begin, end in ((BEGIN_TOP, END_TOP), (BEGIN_DISPATCH, END_DISPATCH)):
        worker, count = _block(begin, end).subn("", worker)
        if count > 1:
            raise PatchError(f"Found {count} copies of the block that starts {begin!r}.")
    for marker in (BEGIN_TOP, END_TOP, BEGIN_DISPATCH, END_DISPATCH):
        if marker in worker:
            raise PatchError(f"Found an unmatched marker {marker!r}. Restore a clean build and run again.")
    return worker


def bundle_body(bundle):
    """The bundle without its final export line, ready to paste."""
    text = bundle.rstrip()
    if "GENERATED FILE" not in text.split("\n", 1)[0] or "const BillWatchHuman = (() => {" not in text:
        raise PatchError("The bundle does not look like dist/billwatch-human.mjs.")
    if not text.endswith(EXPORT_LINE):
        raise PatchError(f"The bundle must end with {EXPORT_LINE!r}.")
    body = text[: -len(EXPORT_LINE)].rstrip()
    if re.search(r"^\s*(import|export)\b", body, re.M):
        raise PatchError("The bundle has an import or export besides its last line.")
    return body


def patch_worker(worker, bundle, homepage=HUMAN_HOMEPAGE):
    """Return the worker text with the human pages added. Idempotent."""
    newline = "\r\n" if "\r\n" in worker else "\n"
    worker = remove_patch(worker.replace("\r\n", "\n"))
    body = bundle_body(bundle.replace("\r\n", "\n"))

    for name in OWN_NAMES:
        if re.search(r"(?<![\w$])" + re.escape(name) + r"(?![\w$])", worker):
            raise PatchError(f"{name} already appears in the worker. Remove the earlier manual patch, or rename it there.")

    fetches = list(FETCH.finditer(worker))
    if len(fetches) != 1:
        lines = ", ".join(str(worker.count("\n", 0, match.start()) + 1) for match in fetches) or "none"
        raise PatchError(f"Expected exactly one 'async fetch(request, env, ctx) {{' line; found {len(fetches)} (lines: {lines}).")
    params = [part.strip() for part in fetches[0].group("params").split(",") if part.strip()]
    if not 2 <= len(params) <= 3 or not all(IDENTIFIER.fullmatch(part) for part in params):
        raise PatchError(f"Unexpected fetch parameters: {fetches[0].group('params')!r}.")
    request, env, ctx = (params + ["undefined"])[:3]
    if len(EXPORT_DEFAULT.findall(worker)) != 1:
        raise PatchError("Expected exactly one 'export default' line.")
    if worker[fetches[0].end():fetches[0].end() + 1] != "\n":
        raise PatchError("The fetch line must end with a line break.")

    indent = fetches[0].group("indent") + "  "
    dispatch = "".join(f"{indent}{line}\n" for line in (
        BEGIN_DISPATCH,
        f"const humanResponse = await BillWatchHuman.handleHumanRequest({request}, {env}, {ctx}, {{ homepage: HUMAN_HOMEPAGE }});",
        "if (humanResponse) return humanResponse;",
        END_DISPATCH,
    ))
    cut = fetches[0].end() + 1  # just after the fetch line's newline
    worker = worker[:cut] + dispatch + worker[cut:]

    top = "\n".join((
        BEGIN_TOP,
        body,
        "",
        "// Homepage switch, set by HUMAN_HOMEPAGE in billwatch_human_patch.py. Do not edit here.",
        f"const HUMAN_HOMEPAGE = {'true' if homepage else 'false'};",
        END_TOP,
    )) + "\n"
    at = EXPORT_DEFAULT.search(worker).start()
    worker = worker[:at] + top + worker[at:]
    return worker.replace("\n", newline)


def main(argv=None):
    parser = argparse.ArgumentParser(description="Add the BillWatch human pages to an assembled _worker.js.")
    parser.add_argument("worker", type=Path, help="the assembled _worker.js, rewritten in place")
    parser.add_argument("bundle", type=Path, nargs="?", default=Path(__file__).with_name("billwatch-human.mjs"),
                        help="dist/billwatch-human.mjs (default: next to this script)")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="exit 1 unless the worker is already patched; write nothing")
    mode.add_argument("--remove", action="store_true", help="take the human pages back out")
    parser.add_argument("--homepage", choices=("on", "off"), help="override HUMAN_HOMEPAGE for this run")
    args = parser.parse_args(argv)
    homepage = HUMAN_HOMEPAGE if args.homepage is None else args.homepage == "on"

    try:
        original = args.worker.read_bytes().decode("utf-8")
        if args.remove:
            result = remove_patch(original.replace("\r\n", "\n"))
            if "\r\n" in original:
                result = result.replace("\n", "\r\n")
        else:
            result = patch_worker(original, args.bundle.read_bytes().decode("utf-8"), homepage)
    except (OSError, UnicodeDecodeError, PatchError) as error:
        print(f"billwatch_human_patch: {error}", file=sys.stderr)
        return 2

    if args.check:
        if result == original:
            print(f"{args.worker} includes the BillWatch human pages (homepage switch {'on' if homepage else 'off'}).")
            return 0
        print(f"{args.worker} does not include this version of the BillWatch human pages. Run the script without --check.", file=sys.stderr)
        return 1
    if result != original:
        args.worker.write_bytes(result.encode("utf-8"))
    action = "Removed the BillWatch human pages from" if args.remove else "Patched"
    print(f"{action} {args.worker}" + ("" if args.remove else f" (homepage switch {'on' if homepage else 'off'})."))
    return 0


if __name__ == "__main__":
    sys.exit(main())
